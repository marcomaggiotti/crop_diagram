@app.get("/health", tags=["ops"])
def health() -> dict:
    """Liveness probe — returns 200 OK when the service is ready."""
    return {"status": "ok"}


@app.post(
    "/crop",
    tags=["processing"],
    summary="Extract EG diagram crops from a PDF",
    response_description="ZIP archive: PNG crops + metadata.json",
)
async def crop_pdf(
    file: Annotated[UploadFile, File(description="PDF to process")],
    dpi: Annotated[float, Query(ge=72, le=400, description="Rasterisation DPI")] = 200,
    pad: Annotated[int, Query(ge=0, le=200, description="Padding around each crop (px)")] = 25,
    min_w: Annotated[int, Query(ge=1, description="Min crop width (px)")] = 60,
    min_h: Annotated[int, Query(ge=1, description="Min crop height (px)")] = 80,
    max_w_frac: Annotated[float, Query(ge=0.1, le=1.0, description="Max crop width as fraction of page")] = 0.82,
) -> StreamingResponse:
    """
    Upload a PDF; receive a ZIP containing:

    - `eg_000_page02.png`, `eg_001_page03.png`, … — one PNG per detected diagram
    - `metadata.json` — bbox, page, DPI for every crop

    All detection parameters are tunable via query string.
    """
    if file.content_type not in ("application/pdf", "application/octet-stream"):
        raise HTTPException(
            status_code=415,
            detail=f"Expected a PDF, got content-type '{file.content_type}'",
        )

    pdf_bytes = await file.read()
    if not pdf_bytes:
        raise HTTPException(status_code=400, detail="Uploaded file is empty")

    log.info(
        "Processing '%s'  size=%d bytes  dpi=%.0f  pad=%d",
        file.filename, len(pdf_bytes), dpi, pad,
    )

    try:
        metadata, crops = process_pdf(
            pdf_bytes, dpi=dpi, pad=pad,
            min_w=min_w, min_h=min_h, max_w_frac=max_w_frac,
        )
    except Exception as exc:
        log.exception("Processing failed")
        raise HTTPException(status_code=500, detail=f"Processing failed: {exc}") from exc

    if not crops:
        raise HTTPException(
            status_code=422,
            detail="No diagram regions detected. Try adjusting dpi / min_w / min_h.",
        )

    # Build ZIP in memory
    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for fname, png_bytes in crops:
            zf.writestr(fname, png_bytes)
        zf.writestr("metadata.json", json.dumps(metadata, indent=2))
    zip_buffer.seek(0)

    stem = Path(file.filename or "output").stem
    zip_name = f"{stem}_crops.zip"
    log.info("Returning ZIP '%s' with %d crops", zip_name, len(crops))

    return StreamingResponse(
        zip_buffer,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{zip_name}"'},
    )